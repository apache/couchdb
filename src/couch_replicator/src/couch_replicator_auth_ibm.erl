            ?assertNotEqual(Token1, Token2)
        end
    ).

wait_for_refresh(_APIKeyMAC, OriginalToken, 0) ->
    OriginalToken;
wait_for_refresh(APIKeyMAC, OriginalToken, RetriesLeft) ->
    {ok, NewToken} = gen_server:call(?MODULE, {get_token, APIKeyMAC}),
    if
        OriginalToken == NewToken ->
            timer:sleep(100),
            wait_for_refresh(APIKeyMAC, OriginalToken, RetriesLeft - 1);
        true ->
            NewToken
    end.

