    end).

fake_iam_server_start() ->
    {ok, Pid} = mochiweb_http:start([{port, 0}, {loop, fun fake_iam_server_loop/1}]),
    {Pid, mochiweb_socket_server:get(Pid, port)}.

fake_iam_server_stop(Pid) ->
    mochiweb_http:stop(Pid).

fake_iam_server_loop(Req) ->
    case {mochiweb_request:get(method, Req), mochiweb_request:get(path, Req)} of
        {'POST', "/identity/token"} ->
            RespBody = #{
                ~"access_token" => binary:encode_hex(crypto:strong_rand_bytes(16)),
                ~"expires_in" => 3
            },
            mochiweb_request:ok({"application/json", [], jiffy:encode(RespBody)}, Req);
        _ ->
            mochiweb_request:not_found(Req)
    end.

-endif.
