% This module allows a replication source or target to use an IAM api key for authentication.
%
% Features;
%
% Automatic refreshing of time-limited token before expiration
% Deduplication - only one token will be acquired for each distinct IAM api key
%
% Implementation details
%
% As api keys are sensitive, the only copy of api keys is held in a private ETS table
% owned by this module's gen_server. An opaque reference is returned to clients (this is
% a message authentication code where the key is a non-persisted value generated by the
% gen_server)

-module(couch_replicator_auth_ibm).

-behaviour(couch_replicator_auth).
-behaviour(gen_server).
-behaviour(config_listener).

-export([
    sup_initialize/0,
    sup_cleanup/1,
    initialize/1,
    update_headers/2,
    handle_response/3,
    cleanup/1
]).

%% gen_server callbacks
-export([
    init/1,
    handle_call/3,
    handle_cast/2,
    handle_info/2,
    terminate/2
]).

% config_listener callbacks
-export([
    handle_config_change/5,
    handle_config_terminate/3
]).

-include_lib("couch_replicator/include/couch_replicator_api_wrap.hrl").

-define(MINUTE, 60).
-define(PUBLIC, couch_replicator_auth_ibm_public).
-define(PRIVATE, couch_replicator_auth_ibm_private).

-record(worker_state, {
    api_key_mac,
    last_used
}).

-record(state, {
    mac_key,
    token_uri_map
}).

-record(public_entry, {
    api_key_mac,
    token
}).

-record(private_entry, {
    api_key_mac,
    api_key_uuid,
    api_key,
    expires_ref,
    acquire_mref,
    last_used,
    refresh_ref,
    token_updated_at,
    waiters = []
}).

%% callbacks

sup_initialize() ->
    application:ensure_all_started(gun),
    {ok, _} = gen_server:start_link({local, ?MODULE}, ?MODULE, [], []).

sup_cleanup(_) ->
    ok = gen_server:stop(?MODULE).

initialize(#httpdb{} = HttpDb) ->
    case extract_api_key(HttpDb) of
        {ok, APIKey} ->
            case gen_server:call(?MODULE, {register, APIKey}) of
                {ok, APIKeyMAC} ->
                    WorkerState = #worker_state{api_key_mac = APIKeyMAC, last_used = now_secs()},
                    {ok, HttpDb, WorkerState};
                {error, Reason} ->
                    {error, Reason}
            end;
        {error, _} ->
            ignore
    end.

update_headers(WorkerState, Headers) when is_list(Headers) ->
    case get_token(WorkerState) of
        {ok, Token} ->
            {
                [{~"Authorization", <<"Bearer ", Token/binary>>} | Headers],
                update_last_used(WorkerState)
            };
        {error, Reason} ->
            couch_log:warning("Error when retrieving token: ~p", [Reason]),
            {Headers, WorkerState}
    end.

handle_response(WorkerState, _StatusCode, _Headers) ->
    {continue, WorkerState}.

cleanup(_WorkerState) ->
    ok.

get_token(#worker_state{} = WorkerState) ->
    #worker_state{api_key_mac = APIKeyMAC} = WorkerState,
    case ets:lookup(?PUBLIC, APIKeyMAC) of
        [#public_entry{token = Token}] when is_binary(Token) ->
            {ok, Token};
        [#public_entry{}] ->
            gen_server:call(?MODULE, {get_token, APIKeyMAC}, token_timeout());
        [] ->
            {error, no_token}
    end.

update_last_used(#worker_state{} = WorkerState) ->
    #worker_state{api_key_mac = APIKeyMAC, last_used = LastUsed} = WorkerState,
    Now = now_secs(),
    %% only send a message once per minute at most.
    case Now - LastUsed > ?MINUTE of
        true ->
            ?MODULE ! {update_last_used, APIKeyMAC},
            WorkerState#worker_state{last_used = Now};
        false ->
            WorkerState
    end.

%% gen_server callbacks.

init(_) ->
    case token_uri_map() of
        {ok, TokenURIMap} ->
            ?PUBLIC = ets:new(?PUBLIC, [protected, {keypos, #public_entry.api_key_mac}, named_table]),
            ?PRIVATE = ets:new(?PRIVATE, [
                private, {keypos, #private_entry.api_key_mac}, named_table
            ]),
            ok = config:listen_for_changes(?MODULE, nil),
            start_gun(#state{
                mac_key = crypto:strong_rand_bytes(32),
                token_uri_map = TokenURIMap
            });
        {error, Reason} ->
            {error, Reason}
    end.

handle_call({register, APIKey}, _From, State) ->
    case ets:match_object(?PRIVATE, #private_entry{api_key = APIKey, _ = '_'}) of
        [#private_entry{} = Entry] ->
            self() ! {update_last_used, Entry#private_entry.api_key_mac},
            {reply, {ok, Entry#private_entry.api_key_mac}, State};
        [] ->
            AcquireMRef = acquire_token(APIKey, State),
            APIKeyMAC = mac(State#state.mac_key, APIKey),
            true = ets:insert_new(?PUBLIC, #public_entry{
                api_key_mac = APIKeyMAC
            }),
            true = ets:insert_new(?PRIVATE, #private_entry{
                api_key = APIKey,
                api_key_mac = APIKeyMAC,
                acquire_mref = AcquireMRef,
                last_used = now_secs()
            }),
            {reply, {ok, APIKeyMAC}, State}
    end;
handle_call({get_token, APIKeyMAC}, From, State) ->
    case ets:lookup(?PUBLIC, APIKeyMAC) of
        [] ->
            {reply, {error, no_such_api_key}, State};
        [#public_entry{token = Token}] when Token /= undefined ->
            {reply, {ok, Token}, State};
        [#public_entry{}] ->
            [#private_entry{} = Entry] = ets:lookup(?PRIVATE, APIKeyMAC),
            ets:insert(?PRIVATE, Entry#private_entry{waiters = [From | Entry#private_entry.waiters]}),
            case Entry of
                #private_entry{acquire_mref = AcquireMRef} when AcquireMRef /= undefined ->
                    ok;
                #private_entry{} ->
                    self() ! {refresh_token, APIKeyMAC}
            end,
            {noreply, State}
    end;
handle_call(_Msg, _From, State) ->
    {reply, {error, unexpected_msg}, State}.

handle_cast(_Msg, State) ->
    {noreply, State}.

handle_info({update_last_used, APIKeyMAC}, State) ->
    ets:update_element(?PRIVATE, APIKeyMAC, {#private_entry.last_used, now_secs()}),
    {noreply, State};
handle_info({refresh_token, APIKeyMAC}, State) ->
    case ets:lookup(?PRIVATE, APIKeyMAC) of
        [] ->
            ok;
        [#private_entry{acquire_mref = undefined} = Entry] ->
            case Entry#private_entry.last_used > Entry#private_entry.token_updated_at of
                true ->
                    couch_log:notice("~p: refreshing api key ~s", [
                        ?MODULE, Entry#private_entry.api_key_uuid
                    ]),
                    AcquireMRef = acquire_token(Entry#private_entry.api_key, State),
                    ets:insert(?PRIVATE, Entry#private_entry{acquire_mref = AcquireMRef});
                false ->
                    %% let it expire
                    ok
            end;
        [#private_entry{}] ->
            ok
    end,
    {noreply, State};
handle_info({expire_api_key_entry, APIKeyMAC}, State) ->
    case ets:lookup(?PRIVATE, APIKeyMAC) of
        [] ->
            ok;
        [#private_entry{} = Entry] ->
            couch_log:warning("~p: api key entry ~s passed expiration time", [
                ?MODULE, Entry#private_entry.api_key_uuid
            ]),
            ets:delete(?PUBLIC, APIKeyMAC),
            ets:delete(?PRIVATE, APIKeyMAC),
            cancel_timer(Entry#private_entry.refresh_ref),
            cancel_timer(Entry#private_entry.expires_ref),
            reply_all(Entry, {error, expired_api_key_entry})
    end,
    {noreply, State};
handle_info({'DOWN', AcquireMRef, process, _AcquirePid, {error, Reason}}, #state{} = State) ->
    case match_on_acquire_mref(AcquireMRef) of
        [#private_entry{} = Entry] ->
            reply_and_reset(Entry, {error, Reason});
        [] ->
            ok
    end,
    {noreply, State};
handle_info(
    {'DOWN', AcquireMRef, process, _AcquirePid, {ok, StatusCode, _ResponseHeaders, ResponseBody}},
    #state{} = State
) ->
    case match_on_acquire_mref(AcquireMRef) of
        [#private_entry{} = Entry] ->
            case StatusCode of
                200 ->
                    case decode_iam_response(ResponseBody) of
                        {ok, Token, ExpiresInMs} ->
                            UUID = api_key_uuid(Token),
                            couch_log:notice("~p: refreshed api key ~s", [
                                ?MODULE, UUID
                            ]),
                            cancel_timer(Entry#private_entry.refresh_ref),
                            cancel_timer(Entry#private_entry.expires_ref),

                            RefreshRef = erlang:send_after(
                                max(
                                    min_refresh_ms(),
                                    ExpiresInMs - early_refresh_ms() - rand:uniform(jitter_ms())
                                ),
                                self(),
                                {refresh_token, Entry#private_entry.api_key_mac}
                            ),
                            ExpiresRef = erlang:send_after(
                                ExpiresInMs,
                                self(),
                                {expire_api_key_entry, Entry#private_entry.api_key_mac}
                            ),
                            true = ets:insert(?PUBLIC, #public_entry{
                                api_key_mac = Entry#private_entry.api_key_mac,
                                token = Token
                            }),
                            reply_and_reset(
                                Entry#private_entry{
                                    api_key_uuid = UUID,
                                    expires_ref = ExpiresRef,
                                    refresh_ref = RefreshRef,
                                    token_updated_at = now_secs()
                                },
                                {ok, Token}
                            );
                        {error, Reason} ->
                            couch_log:notice("~p: failed to refresh api key ~s: ~p", [
                                ?MODULE, Entry#private_entry.api_key_uuid, Reason
                            ]),
                            reply_and_reset(Entry, {error, Reason})
                    end;
                StatusCode ->
                    ErrorMessage = extract_error_message(ResponseBody),
                    couch_log:notice("~p: failed to refresh api key ~s: ~p", [
                        ?MODULE, Entry#private_entry.api_key_uuid, ErrorMessage
                    ]),
                    case StatusCode of
                        500 ->
                            erlang:send_after(
                                min_refresh_ms(),
                                self(),
                                {refresh_token, Entry#private_entry.api_key_mac}
                            );
                        _ ->
                            ok
                    end,
                    reply_and_reset(Entry, {error, ErrorMessage})
            end;
        [] ->
            ok
    end,
    {noreply, State};
handle_info(restart_config_listener, State) ->
    ok = config:listen_for_changes(?MODULE, nil),
    {noreply, State};
handle_info(token_url_change, State0) ->
    case token_uri_map() of
        {ok, TokenURIMap} ->
            stop_gun(State0),
            case start_gun(State0#state{token_uri_map = TokenURIMap}) of
                {ok, State1} ->
                    {noreply, State1};
                {error, Reason} ->
                    {stop, Reason, State0}
            end;
        {error, Reason} ->
            {stop, Reason, State0}
    end;
handle_info(Msg, State) ->
    couch_log:warning("~p: unexpected info ~p", [?MODULE, Msg]),
    {noreply, State}.

terminate(_Reason, State) ->
    stop_gun(State),
    ets:foldl(
        fun(#private_entry{} = Entry, Acc) ->
            cancel_timer(Entry#private_entry.refresh_ref),
            cancel_timer(Entry#private_entry.expires_ref),
            lists:foreach(
                fun(W) -> gen_server:reply(W, {error, terminated}) end,
                Entry#private_entry.waiters
            ),
            Acc
        end,
        ok,
        ?PRIVATE
    ).

%% config_listener functions.

handle_config_change("ibm", "token_url", _, _, State) ->
    ?MODULE ! token_url_change,
    {ok, State};
handle_config_change(_, _, _, _, State) ->
    {ok, State}.

handle_config_terminate(_, stop, _) ->
    ok;
handle_config_terminate(_Server, _Reason, _State) ->
    erlang:send_after(5000, ?MODULE, restart_config_listener).

%% private functions.

now_secs() ->
    erlang:monotonic_time(second).

extract_api_key(#httpdb{auth_props = AuthProps}) ->
    case proplists:get_value(~"ibm", AuthProps) of
        {IBMProps} when is_list(IBMProps) ->
            case proplists:get_value(~"apikey", IBMProps) of
                APIKey when is_binary(APIKey), byte_size(APIKey) > 0 ->
                    {ok, APIKey};
                _ ->
                    {error, missing_api_key}
            end;
        _ ->
            {error, missing_api_key}
    end.

acquire_token(APIKey, #state{} = State) ->
    Headers = [
        {~"content-type", ~"application/x-www-form-urlencoded"},
        host_header(State)
    ],
    Body = mochiweb_util:urlencode([
        {~"grant_type", ~"urn:ibm:params:oauth:grant-type:apikey"},
        {~"response_type", ~"cloud_iam"},
        {~"apikey", APIKey}
    ]),
    #{path := Path} = State#state.token_uri_map,
    {_Pid, Ref} = spawn_monitor(
        post(fix_path(Path), Headers, Body)
    ),
    Ref.

post(Path, ReqHeaders, ReqBody) ->
    post(Path, ReqHeaders, ReqBody, 5).

post(Path, ReqHeaders, ReqBody, RemainingTries) ->
    fun() ->
        case gun_pool:post(Path, ReqHeaders, ReqBody) of
            {async, PoolStreamRef} ->
                Timeout = config:get_integer("ibm", "request_timeout", 30000),
                case gun_pool:await(PoolStreamRef, Timeout) of
                    {response, fin, StatusCode, _RespHeaders} ->
                        exit({error, {unexpected_status_code, StatusCode}});
                    {response, nofin, StatusCode, RespHeaders} ->
                        case gun_pool:await_body(PoolStreamRef, Timeout) of
                            {ok, RespBody} ->
                                exit({ok, StatusCode, RespHeaders, RespBody});
                            {error, Reason} ->
                                exit({error, Reason})
                        end
                end;
            {error, no_connection_available, _Reason} when RemainingTries > 0 ->
                timer:sleep(1000),
                post(Path, ReqHeaders, ReqBody, RemainingTries - 1);
            {error, _Type, Reason} ->
                exit({error, Reason})
        end
    end.

host_header(#state{} = State) ->
    #{host := Host} = State#state.token_uri_map,
    Port = maps:get(port, State#state.token_uri_map, undefined),
    case Port of
        undefined ->
            {~"host", Host};
        _ when is_integer(Port) ->
            {~"host", [Host, $:, integer_to_list(Port)]}
    end.

fix_path([]) ->
    ~"/";
fix_path(Path) when is_binary(Path), byte_size(Path) > 0 ->
    Path;
fix_path(Path) when is_list(Path), length(Path) > 0 ->
    Path.

decode_iam_response(ResponseBody) ->
    try jiffy:decode(ResponseBody, [return_maps]) of
        Decoded when is_map(Decoded) ->
            Token = maps:get(~"access_token", Decoded, undefined),
            ExpiresInSecs = maps:get(~"expires_in", Decoded, undefined),
            if
                is_binary(Token) andalso is_integer(ExpiresInSecs) ->
                    {ok, Token, ExpiresInSecs * 1000};
                true ->
                    {error, malformed_iam_response}
            end;
        _ ->
            {error, malformed_iam_response}
    catch
        _:_ ->
            {error, malformed_iam_response}
    end.

extract_error_message(ResponseBody) ->
    try jiffy:decode(ResponseBody, [return_maps]) of
        #{~"errorCode" := ErrorCode, ~"errorMessage" := ErrorMessage} ->
            {ErrorCode, ErrorMessage};
        _ ->
            malformed_iam_response
    catch
        _:_ ->
            malformed_iam_response
    end.

api_key_uuid(EncodedToken) when is_binary(EncodedToken) ->
    case binary:split(EncodedToken, ~".", [global]) of
        [_Header, Payload, _Signature] ->
            case b64url:decode(Payload) of
                {error, _Reason} ->
                    ~"";
                Decoded when is_binary(Decoded) ->
                    case jiffy:decode(Decoded, [return_maps]) of
                        #{~"apikey_uuid" := UUID} ->
                            UUID;
                        _ ->
                            ~""
                    end
            end;
        _ ->
            ~""
    end.

-spec token_uri_map() -> {ok, uri_string:uri_map()} | {error, term()}.
token_uri_map() ->
    URI = config:get("ibm", "token_url", "https://iam.cloud.ibm.com/identity/token"),
    case uri_string:parse(URI) of
        #{} = URIMap ->
            {ok, URIMap};
        {error, Reason, _Details} ->
            {error, Reason}
    end.

token_timeout() ->
    config:get_integer("ibm", "token_timeout", 30000).

match_on_acquire_mref(AcquireMRef) ->
    ets:match_object(?PRIVATE, #private_entry{acquire_mref = AcquireMRef, _ = '_'}).

-spec reply_and_reset(Entry :: #private_entry{}, Reply :: term()) -> ok.
reply_and_reset(#private_entry{} = Entry, Reply) ->
    ets:insert(?PRIVATE, Entry#private_entry{
        acquire_mref = undefined,
        waiters = []
    }),
    reply_all(Entry, Reply).

-spec reply_all(Entry :: #private_entry{}, Reply :: term()) -> ok.
reply_all(#private_entry{} = Entry, Reply) ->
    lists:foreach(
        fun(W) -> gen_server:reply(W, Reply) end,
        Entry#private_entry.waiters
    ).

cancel_timer(undefined) ->
    ok;
cancel_timer(TimerRef) when is_reference(TimerRef) ->
    erlang:cancel_timer(TimerRef).

start_gun(#state{} = State) ->
    #{host := Host, scheme := Scheme} = State#state.token_uri_map,
    Port = port(State#state.token_uri_map),
    ConnOptions = #{
        transport => transport(Scheme), tls_opts => [{cacerts, couch_replicator_utils:cacert_get()}]
    },
    case gun_pool:start_pool(Host, Port, #{size => 5, conn_opts => ConnOptions}) of
        {ok, PoolPid} ->
            gun_pool:await_up(PoolPid),
            {ok, State};
        {error, Reason} ->
            {error, Reason}
    end.

stop_gun(#state{} = State) ->
    #{host := Host, scheme := Scheme} = State#state.token_uri_map,
    Port = port(State#state.token_uri_map),
    gun_pool:stop_pool(Host, Port, #{transport => transport(Scheme)}).

port(#{port := Port}) ->
    Port;
port(#{scheme := "https"}) ->
    443.

transport("http") ->
    tcp;
transport("https") ->
    tls.

mac(Key, Data) when is_binary(Key), is_binary(Data) ->
    crypto:mac(hmac, sha256, Key, Data).

early_refresh_ms() ->
    max(0, 1000 * config:get_integer("ibm", "early_refresh_secs", 300)).

jitter_ms() ->
    max(1000, 1000 * config:get_integer("ibm", "jitter_secs", 60)).

min_refresh_ms() ->
    max(0, 1000 * config:get_integer("ibm", "min_refresh_secs", 10)).

