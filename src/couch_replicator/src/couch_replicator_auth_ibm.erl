test_refresh_token(_) ->
    ?_test(
        begin
            {ok, APIKeyMAC} = gen_server:call(?MODULE, {register, ~"fake_api_key"}),
            {ok, Token1} = gen_server:call(?MODULE, {get_token, APIKeyMAC}),
            timer:sleep(1000),
            ?MODULE ! {update_last_used, APIKeyMAC},
            ?MODULE ! {refresh_token, APIKeyMAC},
            wait_for_refresh(APIKeyMAC, Token1, 10),
